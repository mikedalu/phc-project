// Billing handles invoices and payments.
type Billing struct {
	svc *service.Billing
}

// NewBilling builds the handler.
func NewBilling(svc *service.Billing) *Billing { return &Billing{svc: svc} }

type chargeLine struct {
	ChargeType     string  `json:"chargeType"`
	Description    string  `json:"description"`
	Quantity       float64 `json:"quantity"`
	UnitPriceMinor int64   `json:"unitPriceMinor"`
	ReferenceID    *string `json:"referenceId"`
	ReferenceType  *string `json:"referenceType"`
}

type createInvoiceRequest struct {
	PatientID     string       `json:"patientId"`
	EncounterID   *string      `json:"encounterId"`
	InvoiceType   string       `json:"invoiceType"`
	InvoiceNumber string       `json:"invoiceNumber"`
	Notes         string       `json:"notes"`
	Charges       []chargeLine `json:"charges"`
}

// CreateInvoice handles POST /api/v1/invoices.
func (h *Billing) CreateInvoice(c *gin.Context) {
	actor, ok := middleware.ActorFrom(c)
	if !ok {
		httpx.Unauthorized(c, "UNAUTHENTICATED", "Authentication required.")
		return
	}

	var req createInvoiceRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		httpx.BadRequest(c, "MALFORMED_REQUEST", "Request body must be valid JSON.", nil)
		return
	}

	patientID, err := uuid.Parse(req.PatientID)
	if err != nil {
		httpx.BadRequest(c, "VALIDATION_FAILED", "patientId must be a UUID.", nil)
		return
	}

	var encounterID *uuid.UUID
	if req.EncounterID != nil && *req.EncounterID != "" {
		parsed, err := uuid.Parse(*req.EncounterID)
		if err != nil {
			httpx.BadRequest(c, "VALIDATION_FAILED", "encounterId must be a UUID.", nil)
			return
		}
		encounterID = &parsed
	}

	lines := make([]service.ChargeInput, 0, len(req.Charges))
	for _, line := range req.Charges {
		var refID *uuid.UUID
		if line.ReferenceID != nil && *line.ReferenceID != "" {
			parsed, err := uuid.Parse(*line.ReferenceID)
			if err != nil {
				httpx.BadRequest(c, "VALIDATION_FAILED", "referenceId must be a UUID.", nil)
				return
			}
			refID = &parsed
		}
		lines = append(lines, service.ChargeInput{
			ChargeType: line.ChargeType, Description: line.Description,
			Quantity: line.Quantity, UnitPriceMinor: line.UnitPriceMinor,
			ReferenceID: refID, ReferenceType: line.ReferenceType,
		})
	}

	invoice, err := h.svc.CreateInvoice(c.Request.Context(), service.CreateInvoiceInput{
		ActorID: actor.UserID, PatientID: patientID, EncounterID: encounterID,
		InvoiceType: req.InvoiceType, InvoiceNumber: req.InvoiceNumber,
		Notes: req.Notes, Charges: lines,
	})
	if err != nil {
		httpx.Error(c, err)
		return
	}

	c.JSON(201, gin.H{"data": gin.H{"invoice": gin.H{
		"id": invoice.ID.String(), "invoiceNumber": invoice.InvoiceNumber,
		"patientId": invoice.PatientID.String(), "status": invoice.Status,
		"totalMinor": invoice.TotalMinor,
		"issuedAt":   invoice.IssuedAt.UTC().Format(time.RFC3339),
	}}})
}

type recordPaymentRequest struct {
	// operationId is generated by the DEVICE. It is the idempotency key.
	OperationID   string `json:"operationId"`
	InvoiceID     string `json:"invoiceId"`
	AmountMinor   int64  `json:"amountMinor"`
	PaymentMethod string `json:"paymentMethod"`
	Reference     string `json:"paymentReference"`
	Notes         string `json:"notes"`
	ReceiptNumber string `json:"receiptNumber"`
}

// RecordPayment handles POST /api/v1/payments.
func (h *Billing) RecordPayment(c *gin.Context) {
	actor, ok := middleware.ActorFrom(c)
	if !ok {
		httpx.Unauthorized(c, "UNAUTHENTICATED", "Authentication required.")
		return
	}

	var req recordPaymentRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		httpx.BadRequest(c, "MALFORMED_REQUEST", "Request body must be valid JSON.", nil)
		return
	}

	operationID, err := uuid.Parse(req.OperationID)
	if err != nil {
		httpx.BadRequest(c, "VALIDATION_FAILED", "operationId must be a UUID — it is the idempotency key.", nil)
		return
	}
	invoiceID, err := uuid.Parse(req.InvoiceID)
	if err != nil {
		httpx.BadRequest(c, "VALIDATION_FAILED", "invoiceId must be a UUID.", nil)
		return
	}

	payment, posted, err := h.svc.RecordPayment(c.Request.Context(), service.RecordPaymentInput{
		ActorID: actor.UserID, OperationID: operationID, InvoiceID: invoiceID,
		AmountMinor: req.AmountMinor, Method: req.PaymentMethod,
		Reference: req.Reference, Notes: req.Notes, ReceiptNumber: req.ReceiptNumber,
	})
	if err != nil {
		httpx.Error(c, err)
		return
	}

	status := 201
	if !posted {
		// A replay. 200 rather than 201: nothing was created, and the client
		// should show the SAME receipt it already has.
		status = 200
	}

	c.JSON(status, gin.H{"data": gin.H{
		"duplicate": !posted,
		"payment": gin.H{
			"id": payment.ID.String(), "receiptNumber": payment.ReceiptNumber,
			"amountMinor": payment.AmountMinor, "status": payment.Status,
			"paidAt": payment.PaidAt.UTC().Format(time.RFC3339),
		},
	}})
}

// InvoiceBalance handles GET /api/v1/invoices/:id/balance.
func (h *Billing) InvoiceBalance(c *gin.Context) {
	actor, ok := middleware.ActorFrom(c)
	if !ok {
		httpx.Unauthorized(c, "UNAUTHENTICATED", "Authentication required.")
		return
	}
	invoiceID, err := uuid.Parse(c.Param("id"))
	if err != nil {
		httpx.BadRequest(c, "VALIDATION_FAILED", "Invoice id must be a UUID.", nil)
		return
	}

	balance, err := h.svc.InvoiceBalance(c.Request.Context(), actor.UserID, invoiceID)
	if err != nil {
		httpx.Error(c, err)
		return
	}

	httpx.OK(c, gin.H{
		"invoiceId": balance.InvoiceID.String(), "status": balance.Status,
		"totalMinor": balance.TotalMinor, "paidMinor": balance.PaidMinor,
		"balanceMinor": balance.BalanceMinor,
	})
}

